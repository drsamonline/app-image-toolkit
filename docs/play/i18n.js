  function pick(lang) {
    return TABLES[lang] || EN;
  }

  // Falls back to English, then to the key itself: a missing translation shows
  // a readable English line rather than "opt.foo" on screen.
  function t(lang, key, vars) {
    var table = pick(lang);
    var s = table[key];
    if (s === undefined) s = EN[key];
    if (s === undefined) return key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, function (m, name) {
      return vars[name] === undefined ? m : String(vars[name]);
    });
  }

